export function needLabel(key, lang) {
  const n = NEEDS.find((x) => x.key === key);
  if (n) return n.label[lang] ?? n.label[0];
  return key; // free-text "other" value
}

export function t(lang) {
  const out = {};
  Object.keys(STR).forEach((k) => {
    out[k] = STR[k][lang] ?? STR[k][0];
  });
  return out;
}
